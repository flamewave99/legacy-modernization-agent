// Writes docs/PARITY.md: characterization tests per spec file, and how many already pass against
// the modern app. This script runs no tests. Both columns state what CI enforces:
// - legacy: the whole suite must pass against legacy on every push to migration and main;
// - modern: the tests listed in modern/ratchet.txt must pass against the modern app on every PR.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { forEachTest } from '../.github/scripts/test-ids.mjs';

const root = new URL('../', import.meta.url);
const listing = JSON.parse(
  execFileSync('npx', ['playwright', 'test', '--list', '--reporter=json'], {
    cwd: new URL('tests/characterization/', root),
    encoding: 'utf8',
    env: { ...process.env, INCLUDE_LEGACY_BUGS: '' },
  }),
);

// Same ids as the CI ratchet check, from one shared definition.
const ids = [];
forEachTest(listing, (id) => ids.push(id));

const ratchet = new Set(
  readFileSync(new URL('modern/ratchet.txt', root), 'utf8')
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#')),
);

const byFile = new Map();
for (const id of ids) {
  const file = id.split(' › ')[0];
  const row = byFile.get(file) ?? { total: 0, modern: 0 };
  row.total++;
  if (ratchet.has(id)) row.modern++;
  byFile.set(file, row);
}

const totals = [...byFile.values()].reduce(
  (a, r) => ({ total: a.total + r.total, modern: a.modern + r.modern }),
  { total: 0, modern: 0 },
);
const pct = (x, n) => `${Math.round((100 * x) / n)}%`;
const lines = [
  '# Behavior parity: legacy vs. modern',
  '',
  'Generated by `node scripts/parity-report.mjs`. Rows are the spec files in `tests/characterization/specs`',
  '(tests tagged `@legacy-bug` excluded).',
  'This script runs no tests: both columns state what CI enforces, so a failing build means the numbers here no longer hold.',
  '- **Legacy:** CI runs the whole suite against the legacy app on every push to `migration` and `main`, and fails on any failure.',
  '- **Modern:** CI runs the tests listed in `modern/ratchet.txt` against the modern app on every PR. A listed test that stops passing fails the build.',
  '',
  '| Spec file | Tests | Legacy (CI requires all) | Modern (CI requires ratchet) |',
  '|---|---|---|---|',
  ...[...byFile.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([file, r]) =>
        `| \`${file}\` | ${r.total} | ${r.total} | ${r.modern} (${pct(r.modern, r.total)}) |`,
    ),
  `| **Total** | **${totals.total}** | **${totals.total}** | **${totals.modern} (${pct(totals.modern, totals.total)})** |`,
  '',
];
writeFileSync(new URL('docs/PARITY.md', root), lines.join('\n'));
console.log(lines.slice(8).join('\n'));
