// Writes docs/PARITY.md: characterization tests per spec file, and how many already pass against
// the modern app. "Modern" counts the tests listed in modern/ratchet.txt, which CI runs against the
// modern app on every PR; the legacy column is the whole suite, which CI runs against legacy on
// every push to migration and main.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const listing = JSON.parse(
  execFileSync('npx', ['playwright', 'test', '--list', '--reporter=json'], {
    cwd: new URL('tests/characterization/', root),
    encoding: 'utf8',
    env: { ...process.env, INCLUDE_LEGACY_BUGS: '' },
  }),
);

// Same test id format as .github/scripts/check-ratchet.mjs: "<file> › <describe…> › <title>".
const ids = [];
function walk(suite, titles) {
  const here =
    suite.title && !suite.file?.endsWith(suite.title) ? [...titles, suite.title] : titles;
  for (const spec of suite.specs ?? [])
    ids.push([suite.file ?? spec.file, ...here, spec.title].join(' › '));
  for (const child of suite.suites ?? []) walk({ ...child, file: child.file ?? suite.file }, here);
}
for (const suite of listing.suites ?? []) walk(suite, []);

const ratchet = new Set(
  readFileSync(new URL('modern/ratchet.txt', root), 'utf8')
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#')),
);

const byFile = new Map();
for (const id of ids) {
  const file = id.split(' › ')[0];
  const row = byFile.get(file) ?? { total: 0, modern: 0 };
  row.total++;
  if (ratchet.has(id)) row.modern++;
  byFile.set(file, row);
}

const totals = [...byFile.values()].reduce(
  (a, r) => ({ total: a.total + r.total, modern: a.modern + r.modern }),
  { total: 0, modern: 0 },
);
const pct = (x, n) => `${Math.round((100 * x) / n)}%`;
const lines = [
  '# Behavior parity: legacy vs. modern',
  '',
  'Generated by `node scripts/parity-report.mjs`. Rows are the spec files in `tests/characterization/specs`',
  '(tests tagged `@legacy-bug` excluded).',
  '- **Legacy:** the whole suite, which CI runs against the legacy app on every push to `migration` and `main`.',
  '- **Modern:** tests listed in `modern/ratchet.txt`, which CI runs against the modern app on every PR. A listed test that stops passing fails the build.',
  '',
  '| Spec file | Tests | Pass on legacy | Pass on modern |',
  '|---|---|---|---|',
  ...[...byFile.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([file, r]) =>
        `| \`${file}\` | ${r.total} | ${r.total} | ${r.modern} (${pct(r.modern, r.total)}) |`,
    ),
  `| **Total** | **${totals.total}** | **${totals.total}** | **${totals.modern} (${pct(totals.modern, totals.total)})** |`,
  '',
];
writeFileSync(new URL('docs/PARITY.md', root), lines.join('\n'));
