// Retrieval eval: runs every question in eval/questions.json through each strategy and scores where
// the first chunk from an expected file lands. Writes eval/RESULTS.md (committed) and prints a summary.
//
//   npm run eval                                   # all strategies whose model is indexed
//   npm run eval -- vector:nomic-embed-text hybrid-bm25:nomic-embed-text
//   npm run eval -- --holdout <strategies...>      # held-out set, written to eval/RESULTS-holdout.md
import { readFileSync, writeFileSync } from 'node:fs';
import { config } from './config.js';
import { bm25Search, loadBm25Index, queryTerms } from './bm25.js';
import { fuse, keywordSearch, search, withClient, type SearchHit } from './db.js';
import { OllamaEmbedder } from './embed.js';

interface Question {
  id: string;
  question: string;
  expected: string[];
}

interface Strategy {
  name: string; // e.g. "vector:nomic-embed-text"
  run: (question: string, k: number) => Promise<SearchHit[]>;
}

const K = 10;
const holdout = process.argv.includes('--holdout');
const questionFile = holdout ? 'questions-holdout.json' : 'questions.json';
const resultFile = holdout ? 'RESULTS-holdout.md' : 'RESULTS.md';
const questions = (JSON.parse(readFileSync(new URL(`../eval/${questionFile}`, import.meta.url), 'utf8')) as { questions: Question[] }).questions;

/** Expected suffixes are relative to legacy/src/main/ unless they start with legacy/. */
const isRelevant = (hit: SearchHit, q: Question): boolean =>
  q.expected.some((suffix) => hit.path.endsWith(suffix.startsWith('legacy/') ? suffix : `/${suffix}`));

await withClient(config.databaseUrl, async (client) => {
  const { rows } = await client.query<{ model: string; n: string }>('SELECT model, count(*) AS n FROM chunks GROUP BY model ORDER BY model');
  const models = rows.map((r) => r.model);

  // Lexical search does not depend on the embedding model; build it once over the first model's rows.
  const first = models[0];
  if (!first) throw new Error('The index is empty; run npm run index first.');
  const bm25Index = await loadBm25Index(client, first);
  const bm25 = async (q: string, k: number) => bm25Search(bm25Index, await queryTerms(client, q), k);

  const strategies: Strategy[] = [
    { name: 'keyword:ts_rank', run: (q, k) => keywordSearch(client, first, q, k) },
    { name: 'keyword:bm25', run: bm25 },
    ...models.flatMap((model): Strategy[] => {
      const embedder = new OllamaEmbedder(model, config.ollamaUrl);
      const vector = async (q: string, k: number) => search(client, model, await embedder.embedQuery(q), k);
      return [
        { name: `vector:${model}`, run: vector },
        { name: `hybrid-ts_rank:${model}`, run: async (q, k) => fuse([await vector(q, 50), await keywordSearch(client, model, q, 50)], k) },
        { name: `hybrid-bm25:${model}`, run: async (q, k) => fuse([await vector(q, 50), await bm25(q, 50)], k) },
      ];
    }),
  ];

  const wanted = process.argv.slice(2).filter((a) => a !== '--holdout');
  const selected = wanted.length > 0 ? strategies.filter((s) => wanted.includes(s.name)) : strategies;
  if (selected.length === 0) throw new Error(`No strategy matches ${wanted.join(', ')}; available: ${strategies.map((s) => s.name).join(', ')}`);

  // rank[strategy][question] = 1-based rank of the first relevant chunk, or null if not in the top K.
  const ranks: Record<string, (number | null)[]> = {};
  for (const strategy of selected) {
    ranks[strategy.name] = [];
    for (const q of questions) {
      const hits = await strategy.run(q.question, K);
      const index = hits.findIndex((h) => isRelevant(h, q));
      ranks[strategy.name]?.push(index >= 0 ? index + 1 : null);
    }
  }

  const summary = selected.map((s) => {
    const r = ranks[s.name] ?? [];
    const hitAt = (k: number) => r.filter((x) => x !== null && x <= k).length;
    const mrr = r.reduce<number>((sum, x) => sum + (x === null ? 0 : 1 / x), 0) / r.length;
    return { name: s.name, hit1: hitAt(1), hit3: hitAt(3), hit5: hitAt(5), mrr };
  });

  const n = questions.length;
  const pct = (x: number) => `${x}/${n} (${Math.round((100 * x) / n)}%)`;
  const table = [
    '| Strategy | hit@1 | hit@3 | hit@5 | MRR@10 |',
    '|---|---|---|---|---|',
    ...summary.map((s) => `| \`${s.name}\` | ${pct(s.hit1)} | ${pct(s.hit3)} | ${pct(s.hit5)} | ${s.mrr.toFixed(3)} |`),
  ];
  const perQuestion = [
    `| Question | ${selected.map((s) => `\`${s.name}\``).join(' | ')} |`,
    `|---|${selected.map(() => '---').join('|')}|`,
    ...questions.map((q, i) => `| ${q.id} | ${selected.map((s) => (ranks[s.name]?.[i] ?? '-')).join(' | ')} |`),
  ];

  const report = [
    holdout ? '# Retrieval eval results: held-out set' : '# Retrieval eval results: development set',
    '',
    `Generated by \`npm run eval${holdout ? ' -- --holdout' : ''}\` on ${new Date().toISOString().slice(0, 10)}. ${n} questions from \`eval/${questionFile}\`; a hit is a chunk`,
    'from an expected file. hit@k counts questions whose first relevant chunk ranks within the top k (the MCP tool',
    'returns 5 by default). MRR@10 averages 1/rank of the first relevant chunk (0 when it is not in the top 10).',
    '',
    `With ${n} questions, one question is ${Math.round(100 / n)} percentage points: treat differences of one or two as noise.`,
    '',
    ...table,
    '',
    '## Rank of the first relevant chunk per question ("-" = not in the top 10)',
    '',
    ...perQuestion,
    '',
  ].join('\n');
  writeFileSync(new URL(`../eval/${resultFile}`, import.meta.url), report);
  console.log(table.join('\n'));
  console.log(`\nWrote eval/${resultFile}`);
});
